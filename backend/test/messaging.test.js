const { test } = require('node:test');
const assert = require('node:assert/strict');
const { SMTPServer } = require('smtp-server');
const { spawn } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');
const net = require('net');

const freePort = () => new Promise(resolve => { const s = net.createServer(); s.listen(0, '127.0.0.1', () => { const p = s.address().port; s.close(() => resolve(p)); }); });
test('settings are admin only and SMTP sends and records a message', async t => {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'tnavi-test-'));
  const file = path.join(temp, 'db.json');
  const apiPort = await freePort(), smtpPort = await freePort();
  let received = '';
  const smtp = new SMTPServer({ disabledCommands: ['STARTTLS'], authOptional: false, onAuth(auth, session, callback) { callback(null, { user: auth.username }); }, onData(stream, session, callback) { stream.on('data', x => { received += x; }); stream.on('end', () => callback()); } });
  await new Promise(resolve => smtp.listen(smtpPort, '127.0.0.1', resolve));
  const env = { ...process.env, DATA_FILE: file, PORT: String(apiPort), DB_DRIVER: 'json', JWT_SECRET: 'test-secret', SETTINGS_ENCRYPTION_KEY: 'a'.repeat(64), UPLOAD_DIR: path.join(temp, 'uploads') };
  const seed = spawn(process.execPath, ['src/seed.js'], { cwd: path.join(__dirname, '..'), env });
  await new Promise((resolve, reject) => seed.on('exit', code => code === 0 ? resolve() : reject(new Error('seed failed'))));
  const app = spawn(process.execPath, ['src/index.js'], { cwd: path.join(__dirname, '..'), env });
  t.after(async () => { app.kill(); await new Promise(resolve => smtp.close(resolve)); fs.rmSync(temp, { recursive: true, force: true }); });
  await new Promise((resolve, reject) => { app.stdout.on('data', d => { if (String(d).includes('listening')) resolve(); }); app.on('exit', () => reject(new Error('server stopped'))); });
  const base = `http://127.0.0.1:${apiPort}/api`;
  const req = async (url, method = 'GET', body, token) => { const r = await fetch(base + url, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) }); return { status: r.status, json: await r.json() }; };
  const admin = (await req('/auth/login','POST',{ email:'admin@tnavicrm.com', password:'admin123' })).json.token;
  const employee = (await req('/auth/login','POST',{ email:'employee@tnavicrm.com', password:'employee123' })).json.token;
  assert.equal((await req('/settings','GET',null,employee)).status, 403);
  const settings = await req('/settings','PUT',{ company: { name: 'Test company' }, smtp: { host:'127.0.0.1', port:smtpPort, secure:false, user:'user', password:'secret', fromEmail:'sender@example.com' }, whatsapp:{ accessToken:'secret-token', phoneNumberId:'12345' } },admin);
  assert.equal(settings.status,200);
  assert.ok(!fs.readFileSync(file, 'utf8').includes('secret-token'));
  assert.ok(!fs.readFileSync(file, 'utf8').includes('\"password\": \"secret\"'));
  assert.equal(settings.json.data.smtp.hasPassword,true);
  assert.equal(settings.json.data.smtp.password,undefined);
  assert.equal(settings.json.data.whatsapp.accessToken,undefined);
  await req('/settings','PUT',{ company:{name:'Updated company'}, smtp:{password:''} },admin);
  const saved = (await req('/settings','GET',null,admin)).json.data;
  assert.equal(saved.smtp.hasPassword,true);
  assert.equal(saved.company.name,'Updated company');
  assert.equal((await req('/outbound/email','POST',{to:'bad',subject:'Hi',body:'test'},employee)).status,400);
  const properties = (await req('/properties','GET',null,employee)).json.data;
  const viewer = (await req('/users', 'POST', { name:'Viewer', email:'viewer@example.com', password:'viewer123', role:'viewer' }, admin));
  assert.equal(viewer.status, 201);
  const viewerToken = (await req('/auth/login','POST',{email:'viewer@example.com',password:'viewer123'})).json.token;
  assert.equal((await req('/properties','POST',{name:'Forbidden'},viewerToken)).status,403);
  const privateProperty = (await req('/properties','POST',{name:'Manager only', assignedTo: (await req('/auth/login','POST',{email:'manager@tnavicrm.com',password:'manager123'})).json.user.id},admin)).json.data;
  assert.equal((await req(`/properties/${privateProperty.id}`,'GET',null,employee)).status,404);
  assert.equal((await req(`/properties/${privateProperty.id}`,'PUT',{name:'Hijacked'},employee)).status,404);
  assert.equal((await req(`/properties/${privateProperty.id}`,'GET',null,viewerToken)).status,200);
  assert.equal((await req(`/properties/${properties[0].id}`,'DELETE',null,employee)).status,403);
  const form = new FormData(); form.append('title','Test file'); form.append('propertyId',properties[0].id); form.append('file',new Blob(['private document']), 'example.txt');
  const uploaded = await fetch(base + '/documents/upload', { method:'POST', headers:{Authorization:`Bearer ${employee}`}, body:form });
  assert.equal(uploaded.status,201); const doc = (await uploaded.json()).data;
  assert.equal((await fetch(`http://127.0.0.1:${apiPort}${doc.fileUrl}`)).status,404);
  assert.equal((await fetch(base + `/documents/${doc.id}/download`)).status,401);
  const downloaded = await fetch(base + `/documents/${doc.id}/download`,{headers:{Authorization:`Bearer ${viewerToken}`}});
  assert.equal(await downloaded.text(), 'private document');
  assert.equal((await req(`/documents/${doc.id}`,'DELETE',null,employee)).status,403);
  const editedDoc = await req(`/documents/${doc.id}`, 'PUT', {title:'Updated file', category:'Photo', propertyId:properties[0].id, fileUrl:'/uploads/other-file'}, employee);
  assert.equal(editedDoc.status,200);
  assert.equal(editedDoc.json.data.fileUrl,doc.fileUrl);
  assert.equal((await req(`/documents/${doc.id}`, 'PUT', {title:'Viewer edit'}, viewerToken)).status,403);
  const proposal = await req('/proposals','POST',{title:'Test proposal',propertyId:properties[0].id,proposedRent:12345,stage:'Draft',status:'Draft'},employee);
  assert.equal(proposal.status,201);
  const updated = await req(`/proposals/${proposal.json.data.id}`,'PUT',{title:'Updated proposal',stage:'Negotiation',counterOffers:[{by:'tamper'}]},employee);
  assert.equal(updated.status,200);
  assert.equal(updated.json.data.revisions.length,2);
  assert.deepEqual(updated.json.data.counterOffers,[]);
  const counter = await req(`/proposals/${proposal.json.data.id}/counter-offers`,'POST',{by:'Brand',rent:10000,date:'2026-12-10',notes:'Revised rent'},employee);
  assert.equal(counter.status,201);
  assert.equal(counter.json.data.counterOffers[0].rent,10000);
  assert.equal((await req(`/proposals/${proposal.json.data.id}/counter-offers`,'POST',{by:'Brand',rent:1,date:'2026-12-10'},viewerToken)).status,403);
  const proposalId = proposal.json.data.id;
  assert.equal((await req(`/proposals/${proposalId}/approval`,'POST',{action:'request',note:'Please review'},employee)).json.data.approvalState,'Pending');
  assert.equal((await req(`/proposals/${proposalId}`,'PUT',{title:'Blocked'},employee)).status,409);
  assert.equal((await req(`/proposals/${proposalId}/approval`,'POST',{action:'approve',note:'Self approval'},employee)).status,403);
  const manager = (await req('/auth/login','POST',{email:'manager@tnavicrm.com',password:'manager123'})).json.token;
  assert.equal((await req(`/proposals/${proposalId}/approval`,'POST',{action:'approve',note:''},manager)).status,400);
  const approved = await req(`/proposals/${proposalId}/approval`,'POST',{action:'approve',note:'Commercial terms reviewed'},manager);
  assert.equal(approved.json.data.approvalState,'Approved');
  assert.equal(approved.json.data.approvalHistory.length,2);
  assert.equal((await req(`/proposals/${proposalId}`,'PUT',{title:'Blocked'},manager)).status,409);
  assert.equal((await req(`/proposals/${proposalId}/approval`,'POST',{action:'reopen'},manager)).json.data.approvalState,'Draft');
  assert.equal((await req(`/proposals/${proposalId}/approval`,'POST',{action:'request'},manager)).status,200);
  assert.equal((await req(`/proposals/${proposalId}/approval`,'POST',{action:'approve',note:'Self review'},manager)).status,403);
  const send = await req('/outbound/email','POST',{to:'client@example.com',subject:'Property',body:'Hello property client',propertyId:properties[0].id,documentIds:[doc.id]},employee);
  assert.equal(send.status,200,JSON.stringify(send.json));
  assert.match(received,/Hello property client/);
  assert.match(received,/example.txt/);
  const history = (await req('/communications','GET',null,employee)).json.data;
  assert.ok(history.some(c => c.subject === 'Property' && c.propertyId === properties[0].id));
  assert.equal((await req('/outbound/whatsapp','POST',{to:'bad',body:'hello'},employee)).status,400);
  const scheduled = await req('/reminders','POST',{channel:'email',to:'client@example.com',subject:'Reminder',body:'Please join',sendAt:new Date(Date.now()+3600000).toISOString(),consent:true},employee);
  assert.equal(scheduled.status,201);
  assert.equal((await req('/reminders/'+scheduled.json.data.id+'/cancel','PATCH',{},employee)).json.data.status,'Cancelled');
  assert.equal((await req('/reminders','POST',{channel:'email',to:'client@example.com',subject:'Reminder',body:'Please join',sendAt:new Date(Date.now()+3600000).toISOString()},employee)).status,400);
  assert.equal((await req('/reminders','GET',null,viewerToken)).status,403);
  const cleared = await req('/settings','PUT',{ smtp:{clearPassword:true}, whatsapp:{clearAccessToken:true} },admin);
  assert.equal(cleared.json.data.smtp.hasPassword,false);
  assert.equal(cleared.json.data.whatsapp.hasAccessToken,false);
});
